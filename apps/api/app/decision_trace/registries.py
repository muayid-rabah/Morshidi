class MaterialityClass(str, Enum):
    LEDGER_REQUIRED='LEDGER_REQUIRED'; LEDGER_OPTIONAL='LEDGER_OPTIONAL'; DOMAIN_TRACE_ONLY='DOMAIN_TRACE_ONLY'; NOT_LEDGERED='NOT_LEDGERED'
