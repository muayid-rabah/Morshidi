    EXECUTED='EXECUTED'; VALIDATED='VALIDATED'; REVALIDATED_VALID='REVALIDATED_VALID'; REVALIDATED_INVALID='REVALIDATED_INVALID'; ABSTAINED='ABSTAINED'; FLAGGED_REVIEW='FLAGGED_REVIEW'; SUPERSEDED='SUPERSEDED'
